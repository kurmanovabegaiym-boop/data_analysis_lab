import numpy as np

order_id = np.arange(2001, 2013)
region = np.array([
    "Бишкек", "Ош", "Бишкек", "Каракол", "Ош", "Токмок",
    "Бишкек", "Ош", "Каракол", "Токмок", "Бишкек", "Ош"
])
quantity = np.array([2, 1, 5, 3, 2, 8, 1, 4, 2, 3, 6, 1])
unit_price = np.array([1500, 20000, 800, 5000, 1200, 700, 25000, 3000, 4500, 2000, 900, 18000])
discount = np.array([0.05, 0.10, 0.00, 0.15, 0.05, 0.20, 0.30, 0.10, 0.00, 0.05, 0.50, 0.10])
unit_cost = np.array([1000, 16000, 600, 4000, 900, 500, 18000, 2200, 3500, 1500, 800, 14000])

revenue = quantity * unit_price * (1 - discount)
profit = revenue - quantity * unit_cost

print("--- Базовые цифры ---")
print("Доход по заказам:", revenue)
print("Прибыль по заказам:", profit)
print()

print("--- Задание 1: Простые фильтры ---")

mask_rev = revenue > 10000
mask_qty = quantity >= 3
mask_bishkek = (region == "Бишкек")

print("Заказы с доходом больше 10 тыс:", order_id[mask_rev])
print("Заказы где от 3 штук:", order_id[mask_qty])
print("Заказы из Бишкека:", order_id[mask_bishkek])
print()

print("--- Задание 2: 2 условия из 3 ---")

c1 = discount >= 0.20
c2 = revenue > 10000
c3 = quantity >= 4

check = c1.astype(int) + c2.astype(int) + c3.astype(int)
mask_complex = check >= 2

print("Заказы которые подошли под 2 и больше условия:", order_id[mask_complex])
print("Пояснение: Выбрал такое правило чтобы находить крупные заказы, даже если по какому-то одному пункту они немного не дотянули.")
print()

print("--- Задание 3: Убыточные заказы ---")

loss_mask = profit < 0
loss_orders = order_id[loss_mask]
loss_percent = (loss_mask.sum() / len(order_id)) * 100

print("Заказы ушедшие в минус:", loss_orders)
print(f"Процент убыточных: {loss_percent:.1f}%")
print("Объяснение: Большой доход еще не значит что будет прибыль. Если себестоимость товара почти равна цене или мы дали большую скидку, то мы сработаем в убыток.")
print()


print("--- Задание 4: Скидки и прибыль ---")

high_disc_low_prof = (discount >= 0.20) & (profit <= 0)
print("Заказы со скидкой от 20% и без прибыли:", order_id[high_disc_low_prof])
print("Вывод: Нельзя делать вывод что только скидка виновата в убытках, надо смотреть еще и на закупочную цену.")
print()


print("--- Задание 5: Подозрительные заказы ---")

suspicious_mask = (discount >= 0.30) & (profit <= 0)
print("Странные заказы:", order_id[suspicious_mask])
print("Пояснение: Обычные скидки до 15% можно объяснить акциями, а вот скидка 50% загоняющая в минус может быть ошибкой кассира или менеджера.")
print()

print("--- Задание 6: Сравнение Бишкека и Оша ---")

m_bishkek = region == "Бишкек"
m_osh = region == "Ош"

print("Бишкек:")
print(" - Число заказов:", m_bishkek.sum())
print(f" - Доход: {revenue[m_bishkek].sum():.1f}")
print(" - Из них убыточных:", (profit[m_bishkek] < 0).sum())

print("Ош:")
print(" - Число заказов:", m_osh.sum())
print(f" - Доход: {revenue[m_osh].sum():.1f}")
print(" - Из них убыточных:", (profit[m_osh] < 0).sum())
print()


print("--- Задание 7: Средний доход до и после очистки ---")

avg_all = revenue.mean()
avg_clean = revenue[~suspicious_mask].mean()

print(f"Средний доход (все заказы): {avg_all:.2f}")
print(f"Средний доход (без подозрительных): {avg_clean:.2f}")
print("Вывод: Цифры очень сильно меняются в зависимости от того как фильтровать. Удалять данные сразу нельзя, сначала надо разобраться.")
print()

